export function deepMerge(base, overlay) {
  const out = { ...base };
  for (const k of Object.keys(overlay)) {
    if (
      overlay[k] &&
      typeof overlay[k] === 'object' &&
      !Array.isArray(overlay[k]) &&
      base[k] &&
      typeof base[k] === 'object'
    ) {
      out[k] = deepMerge(base[k], overlay[k]);
    } else {
      out[k] = overlay[k];
    }
  }
  return out;
}
